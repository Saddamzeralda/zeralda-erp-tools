/**
 * 🛠️ Purchasing Intelligence & Automation - Zeralda ERP
 * الربط بين المبيعات المتوقعة وعمليات الشراء التلقائية
 */

(function () {
    const PURCHASING_INTEL_KEY = 'zeralda-purchasing-intelligence';

    // ── نظام الترجمة الموحد ──
    var DICT = {
        stockReplenishment:    { en: 'Stock Replenishment', ar: 'إعادة ملء المخزون', fr: 'Réapprovisionnement du stock' },
        items:                 { en: '{count} Items', ar: '{count} عنصر', fr: '{count} articles' },
        actionRequired:        { en: 'Action Required', ar: 'إجراء مطلوب', fr: 'Action requise' },
        stockOptimal:          { en: 'Stock Optimal', ar: 'المخزون مثالي', fr: 'Stock optimal' },
        optimalAlert:          { en: '✅ All stock levels are optimal based on sales forecasts.', ar: '✅ جميع مستويات المخزون مثالية بناءً على توقعات المبيعات.', fr: '✅ Tous les niveaux de stock sont optimaux selon les prévisions de ventes.' },
        recommendedPurchases:  { en: '📦 Recommended Purchases (Based on AI Forecast):\n\n', ar: '📦 المشتريات الموصى بها (بناءً على توقعات الذكاء الاصطناعي):\n\n', fr: '📦 Achats recommandés (selon la prévision IA) :\n\n' },
        lineItem:              { en: '• {name}: Need {needed} units [Priority: {priority}]\n', ar: '• {name}: مطلوب {needed} وحدة [الأولوية: {priority}]\n', fr: '• {name} : besoin de {needed} unités [Priorité : {priority}]\n' },
        confirmGenerate:       { en: '\nWould you like to auto-generate Purchase Orders for HIGH priority items?', ar: '\nهل تريد إنشاء أوامر شراء تلقائيًا للعناصر ذات الأولوية العالية؟', fr: '\nVoulez-vous générer automatiquement des bons de commande pour les articles à priorité HAUTE ?' },
        purchasingAutomation:  { en: '🚀 Purchasing Automation: New Order created for {name} ({needed} units)', ar: '🚀 أتمتة المشتريات: تم إنشاء طلب جديد لـ {name} ({needed} وحدة)', fr: '🚀 Automatisation des achats : nouvelle commande créée pour {name} ({needed} unités)' },
        autoAssigned:          { en: 'Auto-Assigned', ar: 'مُعيَّن تلقائيًا', fr: 'Attribué automatiquement' },
        high:                  { en: 'High', ar: 'عالية', fr: 'Haute' },
        medium:                { en: 'Medium', ar: 'متوسطة', fr: 'Moyenne' }
    };
    var t = window.createRuntimeTranslator ? window.createRuntimeTranslator(DICT) : function (k) { return k; };

    // 1. Smart Replenishment Planning
    // حساب الكميات المطلوب شراؤها بناءً على توقعات المبيعات وسجل الشراء
    window.suggestReplenishment = function() {
        const forecast = typeof window.getSalesForecast === 'function' ? Number(window.getSalesForecast()) : 0;
        const inventory = safeJSONParse(ZS.getItem('inventory-data'), [] === '{}' ? {} : []);

        const suggestions = inventory.map(item => {
            const currentStock = Number(item.quantity || 0);
            const minStock = Number(item.minQuantity || 5);

            // إذا كانت المبيعات المتوقعة عالية، نرفع حد الأمان
            const safetyBuffer = forecast > 10000 ? 1.5 : 1.2;
            const targetStock = Math.ceil(minStock * safetyBuffer);

            if (currentStock < targetStock) {
                return {
                    productId: item.id,
                    name: item.name,
                    needed: targetStock - currentStock,
                    priority: currentStock <= minStock ? t('high') : t('medium')
                };
            }
            return null;
        }).filter(Boolean);

        return suggestions;
    };

    // 2. Automating RFQ (Request for Quotation)
    window.generateAutoPO = function(suggestion) {
        const purchases = safeJSONParse(ZS.getItem('purchases-data'), [] === '{}' ? {} : []);
        const newPO = {
            id: Date.now(),
            reference: `AUTO-REPLENISH-${Date.now().toString().slice(-4)}`,
            supplier: t('autoAssigned'),
            date: new Date().toISOString().split('T')[0],
            items: [{
                name: suggestion.name,
                qty: suggestion.needed,
                price: 0, // To be filled by procurement
                total: 0
            }],
            status: 'Pending',
            isAutoGenerated: true
        };

        purchases.push(newPO);
        ZS.setItem('purchases-data', JSON.stringify(purchases));
        alert(t('purchasingAutomation', { name: suggestion.name, needed: suggestion.needed }));
        if (window.loadPurchases) window.loadPurchases();
    };

    // 3. UI Injections for Purchasing Intelligence
    window.injectPurchasingIntelUI = function() {
        const statsGrid = document.querySelector('.stats-grid');
        if (statsGrid && !document.getElementById('stockAlertCard')) {
            const suggestions = window.suggestReplenishment();
            const alertCount = suggestions.length;

            const card = document.createElement('div');
            card.id = 'stockAlertCard';
            card.className = 'stat-card';
            card.style.border = alertCount > 0 ? '2px solid var(--danger-color)' : '2px solid var(--success-color)';

            card.innerHTML = `
                <div class="stat-icon ${alertCount > 0 ? 'red' : 'green'}"><i class="fas fa-boxes-stacked"></i></div>
                <div class="stat-details" style="cursor:pointer;" onclick="showReplenishmentDetails()">
                    <p data-en="Stock Replenishment" data-ar="إعادة ملء المخزون" data-fr="Réapprovisionnement du stock">${t('stockReplenishment')}</p>
                    <h3>${t('items', { count: alertCount })}</h3>
                    <div class="stat-change ${alertCount > 0 ? 'negative' : 'positive'}">
                        ${alertCount > 0 ? `<i class="fas fa-exclamation-triangle"></i> ${t('actionRequired')}` : `<i class="fas fa-check"></i> ${t('stockOptimal')}`}
                    </div>
                </div>
            `;
            statsGrid.appendChild(card);
        }
    };

    window.showReplenishmentDetails = function() {
        const suggestions = window.suggestReplenishment();
        if (suggestions.length === 0) {
            alert(t('optimalAlert'));
            return;
        }

        let msg = t('recommendedPurchases');
        suggestions.forEach(s => {
            msg += t('lineItem', { name: s.name, needed: s.needed, priority: s.priority });
        });

        if (confirm(msg + t('confirmGenerate'))) {
            suggestions.filter(s => s.priority === t('high')).forEach(s => window.generateAutoPO(s));
        }
    };

    document.addEventListener('DOMContentLoaded', () => {
        setTimeout(window.injectPurchasingIntelUI, 1000);
    });

})();
